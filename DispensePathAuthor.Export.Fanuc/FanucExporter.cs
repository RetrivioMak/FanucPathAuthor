using System.Globalization;
using System.Text;
using DispensePathAuthor.Contracts;

namespace DispensePathAuthor.Export.Fanuc;

public static class FanucExporter
{
    /// <summary>
    /// Feed used when the caller does not supply one. Fanuc feed passes a speed per point.
    /// </summary>
    private const double DefaultLsSpeed_mm_s = 100;

    public static void ExportLs(
        IReadOnlyList<FanucExportPoint> waypoints,
        string programName,
        string filePath,
        bool applyFrameYReflection = true,
        int userFrame = 1,
        int userTool = 1,
        Func<FanucExportPoint, int, double>? speedMmPerSec = null,
        string? processNote = null)
    {
        IReadOnlyList<FanucExportPoint> exportWaypoints = FilterExportWaypoints(waypoints);
        if (exportWaypoints.Count == 0)
        {
            throw new InvalidOperationException("No waypoints to export.");
        }

        if (exportWaypoints.Any(static wp => double.IsNaN(wp.ExportX_mm) || double.IsNaN(wp.ExportY_mm)))
        {
            throw new InvalidOperationException("Load RobotCvTransformCalibration.json before exporting .LS.");
        }

        string uf = userFrame.ToString(CultureInfo.InvariantCulture);
        string ut = userTool.ToString(CultureInfo.InvariantCulture);
        // eVision local +Y is clockwise from +X. Fanuc UF +Y is counterclockwise.
        // Reflect only that Y axis about the frame origin; leave X, R, and UF as computed.
        // A collinear path does not define Y, so its positions are written unchanged.
        (double X, double Y)[]? frameInverted = applyFrameYReflection
            ? InvertFrameY(exportWaypoints)
            : null;
        IReadOnlyList<LsMotion> motions = BuildMotions(exportWaypoints, frameInverted);

        var sb = new StringBuilder();
        sb.AppendLine($"/PROG  {SanitizeProgramName(programName)}");
        sb.AppendLine("/ATTR");
        sb.AppendLine("OWNER\t= MNEDITOR;");
        sb.AppendLine("COMMENT\t= \"Generated by DispensePathAuthor\";");
        sb.AppendLine("PROG_SIZE\t= 0;");
        sb.AppendLine("CREATE\t= DATE 26-08-11  TIME 12:00:00;");
        sb.AppendLine("MODIFIED\t= DATE 26-08-11  TIME 12:00:00;");
        sb.AppendLine("FILE_NAME\t= ;");
        sb.AppendLine("VERSION\t= 0;");
        sb.AppendLine("LINE_COUNT\t= 0;");
        sb.AppendLine("MEMORY_SIZE\t= 0;");
        sb.AppendLine("PROTECT\t= READ_WRITE;");
        sb.AppendLine("/MN");
        sb.AppendLine($"   1:  UFRAME_NUM={uf} ;");
        sb.AppendLine($"   2:  UTOOL_NUM={ut} ;");

        int lineNo = 3;
        if (!string.IsNullOrWhiteSpace(processNote))
        {
            sb.AppendLine($"   {lineNo++}:  ! {processNote} ;");
        }

        for (int i = 0; i < motions.Count; i++)
        {
            LsMotion motion = motions[i];
            FanucExportPoint target = motion.Target;
            double speed = speedMmPerSec?.Invoke(target, motion.SpeedIndex) ?? DefaultLsSpeed_mm_s;
            if (!double.IsFinite(speed) || speed <= 0)
            {
                throw new InvalidOperationException($"Point P[{target.Index}] has no positive feed speed.");
            }

            string lsSpeed = $"{Format(speed)}mm/sec";
            string termination = i == motions.Count - 1 ? "FINE" : "CNT100";
            string comment = speedMmPerSec == null
                ? $"! Width={Format(target.Width_mm)} Z={Format(target.Z_mm)} ;"
                : $"! Width={Format(target.Width_mm)} Z={Format(target.Z_mm)} Speed={Format(speed)} ;";
            sb.AppendLine($"   {lineNo++}:  {comment}");
            if (motion.Via is FanucExportPoint via)
            {
                sb.AppendLine($"   {lineNo++}:C P[{via.Index}]");
                sb.AppendLine($"    :  P[{target.Index}] {lsSpeed} {termination}    ;");
            }
            else
            {
                sb.AppendLine($"   {lineNo++}:L P[{target.Index}] {lsSpeed} {termination}    ;");
            }
        }

        sb.AppendLine("/POS");
        for (int i = 0; i < exportWaypoints.Count; i++)
        {
            FanucExportPoint wp = exportWaypoints[i];
            double x = wp.ExportX_mm;
            double y = wp.ExportY_mm;
            if (frameInverted != null)
            {
                x = frameInverted[i].X;
                y = frameInverted[i].Y;
            }

            sb.AppendLine($"P[{wp.Index}]{{");
            sb.AppendLine("   GP1:");
            sb.AppendLine($"   UF : {uf}, UT : {ut},");
            sb.AppendLine(
                $"   X = {Format(x)} mm, Y = {Format(y)} mm, Z = {Format(wp.Z_mm)} mm, R = {Format(wp.ExportR_deg)} deg");
            sb.AppendLine("};");
        }

        sb.AppendLine("/END");
        File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
    }

    /// <summary>
    /// Writes the same coordinates the export form produced. The LS Y-axis reflection is not applied.
    /// </summary>
    public static void ExportCsv(
        IReadOnlyList<FanucExportPoint> waypoints,
        string filePath,
        Func<FanucExportPoint, int, double>? speedMmPerSec = null)
    {
        IReadOnlyList<FanucExportPoint> exportWaypoints = FilterExportWaypoints(waypoints);
        var sb = new StringBuilder();
        string header = speedMmPerSec == null
            ? "Index,Role,ExportX_mm,ExportY_mm,Z_mm,ExportR_deg,Width_mm,LocalX_px,LocalY_px,SensorX_px,SensorY_px"
            : "Index,Role,ExportX_mm,ExportY_mm,Z_mm,ExportR_deg,Width_mm,Speed_mm_s,LocalX_px,LocalY_px,SensorX_px,SensorY_px";
        sb.AppendLine(header);

        for (int i = 0; i < exportWaypoints.Count; i++)
        {
            FanucExportPoint wp = exportWaypoints[i];
            sb.Append(wp.Index).Append(',')
                .Append(Escape(wp.Role)).Append(',')
                .Append(Format(wp.ExportX_mm)).Append(',')
                .Append(Format(wp.ExportY_mm)).Append(',')
                .Append(Format(wp.Z_mm)).Append(',')
                .Append(Format(wp.ExportR_deg)).Append(',')
                .Append(Format(wp.Width_mm)).Append(',');
            if (speedMmPerSec != null)
            {
                sb.Append(Format(speedMmPerSec(wp, i))).Append(',');
            }

            sb.Append(Format(wp.LocalX_px)).Append(',')
                .Append(Format(wp.LocalY_px)).Append(',')
                .Append(Format(wp.SensorX_px)).Append(',')
                .Append(Format(wp.SensorY_px))
                .AppendLine();
        }

        File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
    }

    /// <summary>
    /// Fits export mm = origin + lx，ux + ly，uy, then returns origin + lx，ux ? ly，uy.
    /// Null when the local points do not span both frame axes.
    /// </summary>
    private static (double X, double Y)[]? InvertFrameY(IReadOnlyList<FanucExportPoint> waypoints)
    {
        int count = waypoints.Count;
        if (count < 3)
        {
            return null;
        }

        double meanLocalX = 0;
        double meanLocalY = 0;
        double meanExportX = 0;
        double meanExportY = 0;
        for (int i = 0; i < count; i++)
        {
            FanucExportPoint wp = waypoints[i];
            if (!double.IsFinite(wp.LocalX_px) || !double.IsFinite(wp.LocalY_px))
            {
                return null;
            }

            meanLocalX += wp.LocalX_px;
            meanLocalY += wp.LocalY_px;
            meanExportX += wp.ExportX_mm;
            meanExportY += wp.ExportY_mm;
        }

        meanLocalX /= count;
        meanLocalY /= count;
        meanExportX /= count;
        meanExportY /= count;

        double sumXX = 0;
        double sumYY = 0;
        double sumXY = 0;
        double sumXExportX = 0;
        double sumYExportX = 0;
        double sumXExportY = 0;
        double sumYExportY = 0;
        for (int i = 0; i < count; i++)
        {
            FanucExportPoint wp = waypoints[i];
            double localX = wp.LocalX_px - meanLocalX;
            double localY = wp.LocalY_px - meanLocalY;
            sumXX += localX * localX;
            sumYY += localY * localY;
            sumXY += localX * localY;
            sumXExportX += localX * wp.ExportX_mm;
            sumYExportX += localY * wp.ExportX_mm;
            sumXExportY += localX * wp.ExportY_mm;
            sumYExportY += localY * wp.ExportY_mm;
        }

        double determinant = sumXX * sumYY - sumXY * sumXY;
        double scale = Math.Max(sumXX, sumYY);
        if (scale < 1e-6 || Math.Abs(determinant) < 1e-8 * scale * scale)
        {
            return null;
        }

        double axisXX = (sumYY * sumXExportX - sumXY * sumYExportX) / determinant;
        double axisYX = (sumXX * sumYExportX - sumXY * sumXExportX) / determinant;
        double axisXY = (sumYY * sumXExportY - sumXY * sumYExportY) / determinant;
        double axisYY = (sumXX * sumYExportY - sumXY * sumXExportY) / determinant;
        if (!double.IsFinite(axisXX) || !double.IsFinite(axisYX) ||
            !double.IsFinite(axisXY) || !double.IsFinite(axisYY))
        {
            return null;
        }

        double originX = meanExportX - axisXX * meanLocalX - axisYX * meanLocalY;
        double originY = meanExportY - axisXY * meanLocalX - axisYY * meanLocalY;

        var inverted = new (double X, double Y)[count];
        for (int i = 0; i < count; i++)
        {
            FanucExportPoint wp = waypoints[i];
            inverted[i] = (
                originX + axisXX * wp.LocalX_px - axisYX * wp.LocalY_px,
                originY + axisXY * wp.LocalX_px - axisYY * wp.LocalY_px);
        }

        return inverted;
    }

    /// <summary>
    /// Point and line are linear. An arc is one circular move: the robot is already at the start,
    /// passes through the mid point, and stops at the end. A start that repeats the current pose is not a move.
    /// </summary>
    private static List<LsMotion> BuildMotions(
        IReadOnlyList<FanucExportPoint> waypoints,
        (double X, double Y)[]? frameInverted)
    {
        var motions = new List<LsMotion>();
        WrittenPose? pose = null;
        for (int i = 0; i < waypoints.Count; i++)
        {
            FanucExportPoint point = waypoints[i];
            if (IsRole(point, "mid") &&
                i + 1 < waypoints.Count &&
                IsRole(waypoints[i + 1], "end"))
            {
                FanucExportPoint end = waypoints[i + 1];
                if (pose == null)
                {
                    motions.Add(LsMotion.Linear(point, i));
                    pose = Written(point, i, frameInverted);
                    motions.Add(LsMotion.Linear(end, i + 1));
                    pose = Written(end, i + 1, frameInverted);
                }
                else
                {
                    motions.Add(LsMotion.Circular(point, end, i + 1));
                    pose = Written(end, i + 1, frameInverted);
                }

                i++;
                continue;
            }

            WrittenPose written = Written(point, i, frameInverted);
            if (IsRole(point, "start") && pose is WrittenPose current && SamePose(current, written))
            {
                continue;
            }

            motions.Add(LsMotion.Linear(point, i));
            pose = written;
        }

        return motions;
    }

    private static WrittenPose Written(
        FanucExportPoint point,
        int index,
        (double X, double Y)[]? frameInverted)
    {
        double x = point.ExportX_mm;
        double y = point.ExportY_mm;
        if (frameInverted != null)
        {
            x = frameInverted[index].X;
            y = frameInverted[index].Y;
        }

        return new WrittenPose(x, y, point.Z_mm, point.ExportR_deg);
    }

    private static bool SamePose(WrittenPose left, WrittenPose right) =>
        Format(left.X) == Format(right.X) &&
        Format(left.Y) == Format(right.Y) &&
        Format(left.Z) == Format(right.Z) &&
        Format(left.R) == Format(right.R);

    private static bool IsRole(FanucExportPoint point, string role) =>
        point.Role.Equals(role, StringComparison.OrdinalIgnoreCase);

    private readonly record struct LsMotion(FanucExportPoint Target, int SpeedIndex, FanucExportPoint? Via)
    {
        public static LsMotion Linear(FanucExportPoint target, int speedIndex) =>
            new(target, speedIndex, null);

        public static LsMotion Circular(FanucExportPoint via, FanucExportPoint end, int speedIndex) =>
            new(end, speedIndex, via);
    }

    private readonly record struct WrittenPose(double X, double Y, double Z, double R);

    private static IReadOnlyList<FanucExportPoint> FilterExportWaypoints(IReadOnlyList<FanucExportPoint> waypoints) =>
        waypoints.Where(static wp => !wp.IsPreviewOnly).ToList();

    private static string SanitizeProgramName(string name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return "GLUE_PATH";
        }

        var chars = name.Where(static c => char.IsLetterOrDigit(c) || c == '_').ToArray();
        return chars.Length == 0 ? "GLUE_PATH" : new string(chars).ToUpperInvariant();
    }

    private static string Format(double value) =>
        double.IsNaN(value)
            ? string.Empty
            : value.ToString("0.###", CultureInfo.InvariantCulture);

    private static string Escape(string value) =>
        value.Contains(',') ? $"\"{value}\"" : value;
}
