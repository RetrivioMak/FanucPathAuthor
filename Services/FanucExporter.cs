using System.Globalization;
using System.Text;
using FanucPathAuthor.Models;

namespace FanucPathAuthor.Services;

public static class FanucExporter
{
    private const double DefaultLsSpeed_mm_s = 100;

    public static void ExportCsv(IReadOnlyList<RobotWaypoint> waypoints, string filePath)
    {
        IReadOnlyList<RobotWaypoint> exportWaypoints = FilterExportWaypoints(waypoints);
        var sb = new StringBuilder();
        sb.AppendLine("Index,Role,ExportX_mm,ExportY_mm,ExportR_deg,GlueOn,LocalX_px,LocalY_px,SensorX_px,SensorY_px");

        foreach (RobotWaypoint wp in exportWaypoints)
        {
            sb.Append(wp.Index).Append(',')
                .Append(Escape(wp.Role)).Append(',')
                .Append(Format(wp.ExportX_mm)).Append(',')
                .Append(Format(wp.ExportY_mm)).Append(',')
                .Append(Format(wp.ExportR_deg)).Append(',')
                .Append(wp.GlueOn ? "1" : "0").Append(',')
                .Append(Format(wp.LocalX_px)).Append(',')
                .Append(Format(wp.LocalY_px)).Append(',')
                .Append(Format(wp.SensorX_px)).Append(',')
                .Append(Format(wp.SensorY_px))
                .AppendLine();
        }

        File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
    }

    public static void ExportLs(
        IReadOnlyList<RobotWaypoint> waypoints,
        RobotCalibrationFile? calibration,
        string programName,
        string filePath)
    {
        IReadOnlyList<RobotWaypoint> exportWaypoints = FilterExportWaypoints(waypoints);
        if (exportWaypoints.Count == 0)
        {
            throw new InvalidOperationException("No waypoints to export.");
        }

        if (exportWaypoints.Any(static wp => double.IsNaN(wp.ExportX_mm) || double.IsNaN(wp.ExportY_mm)))
        {
            throw new InvalidOperationException("Load RobotCvTransformCalibration.json before exporting .LS.");
        }

        string uf = ParseFrameNumber(calibration?.RobotFrame, defaultNumber: 1);
        string ut = ParseFrameNumber(calibration?.RobotTool, defaultNumber: 1);
        string lsSpeed = $"{Format(DefaultLsSpeed_mm_s)}mm/sec";

        var sb = new StringBuilder();
        sb.AppendLine($"/PROG  {SanitizeProgramName(programName)}");
        sb.AppendLine("/ATTR");
        sb.AppendLine("OWNER\t= MNEDITOR;");
        sb.AppendLine("COMMENT\t= \"Generated by FanucPathAuthor\";");
        sb.AppendLine("PROG_SIZE\t= 0;");
        sb.AppendLine("CREATE\t= DATE 26-08-11  TIME 12:00:00;");
        sb.AppendLine("MODIFIED\t= DATE 26-08-11  TIME 12:00:00;");
        sb.AppendLine("FILE_NAME\t= ;");
        sb.AppendLine("VERSION\t= 0;");
        sb.AppendLine("LINE_COUNT\t= 0;");
        sb.AppendLine("MEMORY_SIZE\t= 0;");
        sb.AppendLine("PROTECT\t= READ_WRITE;");
        sb.AppendLine("/MN");
        sb.AppendLine($"   1:  UFRAME_NUM={uf} ;");
        sb.AppendLine($"   2:  UTOOL_NUM={ut} ;");

        int lineNo = 3;
        for (int i = 0; i < exportWaypoints.Count; i++)
        {
            RobotWaypoint wp = exportWaypoints[i];
            string motion = i == exportWaypoints.Count - 1 ? "FINE" : "CNT100";
            sb.AppendLine(
                $"   {lineNo++}:L P[{wp.Index}] {lsSpeed} {motion}    ;");
        }

        sb.AppendLine("/POS");
        // eVision local +Y is clockwise from +X. Fanuc UF +Y is counterclockwise.
        // Reflect only that Y axis about the frame origin; leave X, R, and UF as computed.
        // A collinear path does not define Y, so its positions are written unchanged.
        (double X, double Y)[]? frameInverted = InvertFrameY(exportWaypoints);
        for (int i = 0; i < exportWaypoints.Count; i++)
        {
            RobotWaypoint wp = exportWaypoints[i];
            double x = wp.ExportX_mm;
            double y = wp.ExportY_mm;
            if (frameInverted != null)
            {
                x = frameInverted[i].X;
                y = frameInverted[i].Y;
            }

            sb.AppendLine($"P[{wp.Index}]{{");
            sb.AppendLine("   GP1:");
            sb.AppendLine($"   UF : {uf}, UT : {ut},");
            sb.AppendLine(
                $"   X = {Format(x)} mm, Y = {Format(y)} mm, R = {Format(wp.ExportR_deg)} deg");
            sb.AppendLine("};");
        }

        sb.AppendLine("/END");
        File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
    }

    /// <summary>
    /// Fits export mm = origin + lx·ux + ly·uy, then returns origin + lx·ux − ly·uy.
    /// Null when the local points do not span both frame axes.
    /// </summary>
    private static (double X, double Y)[]? InvertFrameY(IReadOnlyList<RobotWaypoint> waypoints)
    {
        int count = waypoints.Count;
        if (count < 3)
        {
            return null;
        }

        double meanLocalX = 0;
        double meanLocalY = 0;
        double meanExportX = 0;
        double meanExportY = 0;
        for (int i = 0; i < count; i++)
        {
            RobotWaypoint wp = waypoints[i];
            if (!double.IsFinite(wp.LocalX_px) || !double.IsFinite(wp.LocalY_px))
            {
                return null;
            }

            meanLocalX += wp.LocalX_px;
            meanLocalY += wp.LocalY_px;
            meanExportX += wp.ExportX_mm;
            meanExportY += wp.ExportY_mm;
        }

        meanLocalX /= count;
        meanLocalY /= count;
        meanExportX /= count;
        meanExportY /= count;

        double sumXX = 0;
        double sumYY = 0;
        double sumXY = 0;
        double sumXExportX = 0;
        double sumYExportX = 0;
        double sumXExportY = 0;
        double sumYExportY = 0;
        for (int i = 0; i < count; i++)
        {
            RobotWaypoint wp = waypoints[i];
            double localX = wp.LocalX_px - meanLocalX;
            double localY = wp.LocalY_px - meanLocalY;
            sumXX += localX * localX;
            sumYY += localY * localY;
            sumXY += localX * localY;
            sumXExportX += localX * wp.ExportX_mm;
            sumYExportX += localY * wp.ExportX_mm;
            sumXExportY += localX * wp.ExportY_mm;
            sumYExportY += localY * wp.ExportY_mm;
        }

        double determinant = sumXX * sumYY - sumXY * sumXY;
        double scale = Math.Max(sumXX, sumYY);
        if (scale < 1e-6 || Math.Abs(determinant) < 1e-8 * scale * scale)
        {
            return null;
        }

        double axisXX = (sumYY * sumXExportX - sumXY * sumYExportX) / determinant;
        double axisYX = (sumXX * sumYExportX - sumXY * sumXExportX) / determinant;
        double axisXY = (sumYY * sumXExportY - sumXY * sumYExportY) / determinant;
        double axisYY = (sumXX * sumYExportY - sumXY * sumXExportY) / determinant;
        if (!double.IsFinite(axisXX) || !double.IsFinite(axisYX) ||
            !double.IsFinite(axisXY) || !double.IsFinite(axisYY))
        {
            return null;
        }

        double originX = meanExportX - axisXX * meanLocalX - axisYX * meanLocalY;
        double originY = meanExportY - axisXY * meanLocalX - axisYY * meanLocalY;

        var inverted = new (double X, double Y)[count];
        for (int i = 0; i < count; i++)
        {
            RobotWaypoint wp = waypoints[i];
            inverted[i] = (
                originX + axisXX * wp.LocalX_px - axisYX * wp.LocalY_px,
                originY + axisXY * wp.LocalX_px - axisYY * wp.LocalY_px);
        }

        return inverted;
    }

    private static IReadOnlyList<RobotWaypoint> FilterExportWaypoints(IReadOnlyList<RobotWaypoint> waypoints) =>
        waypoints.Where(static wp => !wp.IsPreviewOnly).ToList();

    private static string ParseFrameNumber(string? label, int defaultNumber)
    {
        if (string.IsNullOrWhiteSpace(label))
        {
            return defaultNumber.ToString(CultureInfo.InvariantCulture);
        }

        int open = label.IndexOf('[', StringComparison.Ordinal);
        int close = label.IndexOf(']', StringComparison.Ordinal);
        if (open >= 0 && close > open &&
            int.TryParse(label.AsSpan(open + 1, close - open - 1), out int number))
        {
            return number.ToString(CultureInfo.InvariantCulture);
        }

        return defaultNumber.ToString(CultureInfo.InvariantCulture);
    }

    private static string SanitizeProgramName(string name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return "GLUE_PATH";
        }

        var chars = name.Where(static c => char.IsLetterOrDigit(c) || c == '_').ToArray();
        return chars.Length == 0 ? "GLUE_PATH" : new string(chars).ToUpperInvariant();
    }

    private static string Format(double value) =>
        double.IsNaN(value)
            ? string.Empty
            : value.ToString("0.###", CultureInfo.InvariantCulture);

    private static string Escape(string value) =>
        value.Contains(',') ? $"\"{value}\"" : value;
}
