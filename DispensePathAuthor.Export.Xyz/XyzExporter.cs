using System.Globalization;
using System.Text;
using System.Text.Json;
using DispensePathAuthor.Contracts;

namespace DispensePathAuthor.Export.Xyz;

public sealed class XyzExporter : IProgramExporter
{
    public const string ExporterId = "xyz";

    public string Id => ExporterId;

    public string MenuLabel => "Export XYZ...";

    public string SettingsTitle => "XYZ";

    public string FileFilter => "XYZ path|*.xyz";

    public string DefaultFileName => "path.xyz";

    public IReadOnlyList<string> RequiredChannels { get; } = ["X", "Y", "Z"];

    public UserControl? CreateSettingsPage() => new XyzSettingsPanel();

    public string? Validate(ProgramExportRequest request)
    {
        if (!string.IsNullOrEmpty(request.TrajectoryError))
        {
            return request.TrajectoryError;
        }

        if (request.Moves.Count == 0)
        {
            return "No segments to export.";
        }

        return null;
    }

    public void Export(ProgramExportRequest request)
    {
        XyzSettings settings = XyzSettings.Read(request.Settings);
        var output = new StringBuilder();
        output.AppendLine("; Generated by DispensePathAuthor");
        output.AppendLine("; exporter xyz");
        output.Append("; channels");
        foreach (string channel in RequiredChannels)
        {
            output.Append(' ').Append(channel);
        }

        output.AppendLine();
        output.AppendLine(string.Create(CultureInfo.InvariantCulture, $"; z_mm {settings.Z_mm:0.000}"));
        output.AppendLine(string.Create(CultureInfo.InvariantCulture, $"; valve {settings.ValveOutput}"));
        foreach (FrameMove move in request.Moves)
        {
            foreach ((double x, double y) in Sample(move, settings.ChordTolerance_mm))
            {
                int valve = move.Width_mm > 0 ? settings.ValveOutput : 0;
                output.AppendLine(string.Create(
                    CultureInfo.InvariantCulture,
                    $"MOVE X{x:0.000} Y{y:0.000} Z{move.Z_mm:0.000} W{move.Width_mm:0.000} V{valve}"));
            }
        }

        File.WriteAllText(request.DestinationPath, output.ToString());
    }

    internal static IReadOnlyList<(double X, double Y)> Sample(FrameMove move, double chordToleranceMm)
    {
        return move.Kind switch
        {
            FrameMoveKind.Dot => [(move.X1, move.Y1)],
            FrameMoveKind.Line => [(move.X1, move.Y1), (move.X2, move.Y2)],
            FrameMoveKind.Arc => SampleArc(move, chordToleranceMm),
            _ => []
        };
    }

    private static IReadOnlyList<(double X, double Y)> SampleArc(FrameMove move, double chordToleranceMm)
    {
        if (!TryCircle(
                move.X1,
                move.Y1,
                move.X2,
                move.Y2,
                move.X3,
                move.Y3,
                out double centerX,
                out double centerY,
                out double radius))
        {
            return [(move.X1, move.Y1), (move.X2, move.Y2), (move.X3, move.Y3)];
        }

        double start = Math.Atan2(move.Y1 - centerY, move.X1 - centerX);
        double mid = Math.Atan2(move.Y2 - centerY, move.X2 - centerX);
        double end = Math.Atan2(move.Y3 - centerY, move.X3 - centerX);
        double sweep = SweepThroughMid(start, mid, end);
        double step = ChordStep(radius, Math.Max(chordToleranceMm, 1e-4));
        int steps = (int)Math.Clamp(Math.Ceiling(Math.Abs(sweep) / step), 2, 2000);
        var points = new List<(double X, double Y)>(steps + 1);
        for (int i = 0; i <= steps; i++)
        {
            double angle = start + sweep * i / steps;
            points.Add((centerX + radius * Math.Cos(angle), centerY + radius * Math.Sin(angle)));
        }

        points[0] = (move.X1, move.Y1);
        points[^1] = (move.X3, move.Y3);
        return points;
    }

    private static double ChordStep(double radius, double tolerance)
    {
        double ratio = Math.Clamp(1 - tolerance / radius, -1, 1);
        double step = 2 * Math.Acos(ratio);
        return step < 1e-4 ? Math.PI / 4 : step;
    }

    private static bool TryCircle(
        double x1,
        double y1,
        double x2,
        double y2,
        double x3,
        double y3,
        out double centerX,
        out double centerY,
        out double radius)
    {
        centerX = 0;
        centerY = 0;
        radius = 0;
        double determinant = 2 * (x1 * (y2 - y3) + x2 * (y3 - y1) + x3 * (y1 - y2));
        if (Math.Abs(determinant) < 1e-9)
        {
            return false;
        }

        double square1 = x1 * x1 + y1 * y1;
        double square2 = x2 * x2 + y2 * y2;
        double square3 = x3 * x3 + y3 * y3;
        centerX = (square1 * (y2 - y3) + square2 * (y3 - y1) + square3 * (y1 - y2)) / determinant;
        centerY = (square1 * (x3 - x2) + square2 * (x1 - x3) + square3 * (x2 - x1)) / determinant;
        radius = Math.Sqrt((x1 - centerX) * (x1 - centerX) + (y1 - centerY) * (y1 - centerY));
        return radius > 1e-9;
    }

    private static double SweepThroughMid(double startAngle, double midAngle, double endAngle)
    {
        double ccwToMid = PositiveSweep(startAngle, midAngle);
        double ccwToEnd = PositiveSweep(startAngle, endAngle);
        if (ccwToEnd < 1e-9)
        {
            ccwToEnd = 2 * Math.PI;
        }

        return ccwToMid <= ccwToEnd + 1e-8 ? ccwToEnd : ccwToEnd - 2 * Math.PI;
    }

    private static double PositiveSweep(double startAngle, double targetAngle)
    {
        double sweep = targetAngle - startAngle;
        while (sweep < 0)
        {
            sweep += 2 * Math.PI;
        }

        while (sweep >= 2 * Math.PI)
        {
            sweep -= 2 * Math.PI;
        }

        return sweep;
    }
}

public sealed class XyzSettings
{
    public double Z_mm { get; init; }

    public int ValveOutput { get; init; } = 1;

    public double ChordTolerance_mm { get; init; } = 0.2;

    public static XyzSettings Read(JsonElement section)
    {
        double z = 0;
        int valve = 1;
        double chord = 0.2;
        if (section.ValueKind == JsonValueKind.Object)
        {
            if (section.TryGetProperty("z_mm", out JsonElement zElement) && zElement.TryGetDouble(out double zValue))
            {
                z = zValue;
            }

            if (section.TryGetProperty("valveOutput", out JsonElement valveElement) && valveElement.TryGetInt32(out int valveValue))
            {
                valve = valveValue;
            }

            if (section.TryGetProperty("chordTolerance_mm", out JsonElement chordElement) &&
                chordElement.TryGetDouble(out double chordValue) &&
                chordValue > 0)
            {
                chord = chordValue;
            }
        }

        return new XyzSettings
        {
            Z_mm = z,
            ValveOutput = valve,
            ChordTolerance_mm = chord
        };
    }
}
